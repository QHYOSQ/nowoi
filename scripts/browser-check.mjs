import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {calculateBudget,validateForm,STORAGE_KEY} from '../src/assets/labs.js';
import foundations from '../src/content/guides-foundations.mjs';
import practice from '../src/content/guides-practice.mjs';
const origin=process.env.TEST_ORIGIN||'http://127.0.0.1:4173';
const output=process.env.QA_OUTPUT_DIR||path.resolve('work','browser-qa');
const browser=await chromium.launch({headless:true,...(process.env.CHROME_EXECUTABLE?{executablePath:process.env.CHROME_EXECUTABLE}:{})});
const context=await browser.newContext({viewport:{width:1440,height:1050},acceptDownloads:true});
const page=await context.newPage();
const errors=[];const requests=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(!r.url().startsWith(origin))requests.push(r.url());});
let checks=0;
const check=(condition,message)=>{assert.ok(condition,message);checks++;};
try{
  await fs.mkdir(output,{recursive:true});
  await page.goto(origin,{waitUntil:'networkidle'});
  await page.screenshot({path:path.join(output,'nowoi-home-desktop.png')});
  check(await page.locator('h1').count()===1,'Home heading');
  await page.locator('.search-open').click();await page.locator('#site-search').fill('表单');
  check(await page.locator('.search-result').count()===1,'Search by actual content');
  await page.keyboard.press('Escape');await page.locator('#search-dialog').waitFor({state:'hidden'});check(!await page.locator('#search-dialog').isVisible(),'Search closes with Escape');
  check(await page.locator('.search-open').evaluate(e=>e===document.activeElement),'Search returns focus');
  await page.goto(origin+'/guides/?topic=build');
  check(await page.locator('.guide-list .guide-row:visible').count()===[...foundations,...practice].filter(g=>g.topic==='build').length,'Topic links apply filter');
  await page.locator('[data-filter=all]').click();check(await page.locator('.guide-list .guide-row:visible').count()===6,'All six guides visible');
  await page.goto(origin+'/guides/readable-data/');await page.locator('.language-switch').click();
  check(new URL(page.url()).pathname==='/en/guides/readable-data/','Language switch preserves guide');
  check(await page.locator('html').getAttribute('lang')==='en','English language metadata');
  await page.goto(origin+'/workshop/');
  await page.locator('[data-csv-input]').fill('Name,Note\r\n"A, B","Line 1\nLine 2"\r\n<svg onload=alert(1)>,""');
  await page.locator('[data-csv-build]').click();
  check(await page.locator('[data-csv-result] tbody tr').count()===2,'CSV quoted multiline and empty fields');
  check(await page.locator('[data-csv-result] svg').count()===0,'CSV input stays text');
  const downloadPromise=page.waitForEvent('download');await page.locator('[data-csv-export=json]').click();
  const download=await downloadPromise;const downloadPath=path.resolve('..','nowoi-csv-export.json');await download.saveAs(downloadPath);
  const exported=JSON.parse(await fs.readFile(downloadPath,'utf8'));
  check(exported[0].Name==='A, B'&&exported[0].Note==='Line 1\nLine 2','JSON export preserves input');
  await page.locator('[data-csv-input]').fill('name,name\na,b');await page.locator('[data-csv-build]').click();
  check(await page.locator('[data-csv-status]').textContent().then(s=>s.includes('重复')),'Duplicate header error');
  await page.locator('[data-csv-sample]').click();await page.locator('[data-csv-build]').click();
  await page.locator('[data-lab-tab=form]').click();await page.locator('[data-demo-form] button[type=submit]').click();
  check(await page.locator('[data-form-field=email]').evaluate(e=>e===document.activeElement),'Invalid form focuses first field');
  check(await page.locator('[data-form-field=email]').getAttribute('aria-invalid')==='true','Programmatic error state');
  await page.locator('[data-form-field=email]').fill('maya+notes@example.com');
  await page.locator('[data-form-field=project]').fill('A small website for our reading club.');
  await page.locator('[data-demo-form] button[type=submit]').click();
  check(await page.locator('[data-form-success]').textContent().then(s=>s.includes('没有发送')),'Successful local validation is honest');
  await page.locator('[data-lab-tab=budget]').click();await page.locator('[data-budget-input=images]').fill('1000');
  check(Number((await page.locator('[data-budget-total]').textContent()).replaceAll(',',''))===1122,'Budget updates from real input');
  check(Math.abs(Number(await page.locator('[data-budget-seconds]').textContent())-.898)<.001,'Budget formula');
  await page.locator('[data-lab-tab=launch]').click();
  check(await page.locator('[data-check-item]').count()===12,'Checklist has twelve real items');
  await page.locator('[data-check-item]').first().check();
  check(await page.evaluate(key=>localStorage.getItem(key),STORAGE_KEY)===null,'No default persistence');
  await page.locator('[data-check-save]').check();
  check(await page.evaluate(key=>localStorage.getItem(key),STORAGE_KEY)!==null,'Explicit opt-in persists');
  await page.reload();check(await page.locator('[data-check-item]').first().isChecked(),'Saved progress restored');
  await page.locator('[data-lab-tab=launch]').click();await page.locator('[data-check-save]').uncheck();
  check(await page.evaluate(key=>localStorage.getItem(key),STORAGE_KEY)===null,'Opt-out deletes record');
  await page.locator('[data-check-reset]').click();check(await page.locator('[data-check-item]:checked').count()===0,'Reset clears progress');
  await page.locator('[data-lab-tab=data]').focus();await page.keyboard.press('ArrowRight');
  check(await page.locator('[data-lab-tab=form]').getAttribute('aria-selected')==='true','Tab keyboard navigation');
  await page.goto(origin+'/en/workshop/?tab=form');await page.locator('[data-demo-form] button[type=submit]').click();
  check(await page.locator('[data-form-error=email]').textContent().then(s=>s.includes('email')),'English errors translated');
  const routes=['/','/en/','/guides/','/en/guides/','/workshop/','/en/workshop/','/checklist/','/en/checklist/','/about/','/en/about/','/privacy/','/en/privacy/','/contact/','/en/contact/',...['readable-data','useful-form-errors','keyboard-first','image-budget','local-first-honestly','first-week'].flatMap(id=>[`/guides/${id}/`,`/en/guides/${id}/`])];
  for(const width of [1440,390]){
    await page.setViewportSize({width,height:900});
    for(const route of routes){await page.goto(origin+route,{waitUntil:'domcontentloaded'});check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`No horizontal overflow: ${width} ${route}`);}
  }
  await page.goto(origin);await page.screenshot({path:path.join(output,'nowoi-home-mobile.png'),fullPage:true});
  await page.locator('.mobile-menu').click();check(await page.locator('#main-nav').isVisible(),'Mobile navigation opens');
  await page.keyboard.press('Escape');check(!await page.locator('#main-nav').isVisible(),'Mobile navigation closes');
  check(errors.length===0,`No browser errors: ${errors.join('; ')}`);
  check(requests.length===0,`No third-party requests: ${requests.join('; ')}`);
  check(validateForm({email:'maya+notes@example.com',project:'A useful local example'},'en').email===undefined,'Plus-address accepted');
  check(calculateBudget({html:0,js:0,css:0,fonts:0,images:300,speed:1.6}).seconds===1.5,'Known transfer example');
  console.log(JSON.stringify({status:'passed',checks,pages:routes.length,viewports:[1440,390],browserErrors:errors.length,thirdPartyRequests:requests.length,screenshots:output}));
}finally{await browser.close();}
